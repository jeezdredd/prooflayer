def lang_or_default(lang: str | None) -> str:
    return lang if lang in LANGS else "en"


def analyzer_name(code: str, lang: str) -> str:
    names = ANALYZERS.get(code)
    if not names:
        return code.replace("_", " ").capitalize()
    return names[1] if lang == "ru" else names[0]


def field_name(field: str | None, lang: str) -> str:
    raw = (field or "").split(".")[-1].split(":")[-1].lower()
    kind = FIELD_KIND.get(raw)
    return COPY[lang]["fields"][kind] if kind else (field or "")


def kind_name(mime: str, lang: str) -> str:
    major = (mime or "").split("/")[0]
    names = KIND.get(major)
    label = (names[1] if lang == "ru" else names[0]) if names else (mime or "-")
    minor = (mime or "").split("/")[-1].split(".")[-1].split("+")[0].upper()
    if major == "application" and minor in ("PDF", "DOCUMENT"):
        return f"{label} · {'DOCX' if minor == 'DOCUMENT' else 'PDF'}"
    return f"{label} · {minor}" if minor and minor != major.upper() else label


def tone_set(name: str) -> dict:
    color = TONES.get(name, TONES["ink"])
    r, g, b = int(color[1:3], 16), int(color[3:5], 16), int(color[5:7], 16)
    return {"tone": color, "tone_line": f"rgba({r},{g},{b},0.4)", "tone_bg": f"rgba({r},{g},{b},0.08)"}
